# ------------------------------------------------------------------
# Helper: build a group parameter dict from cfg values
# ------------------------------------------------------------------
def _build_par(var_n_key, var_v_key, repl, tau_educ, tau_parent, a0=0.0):
    var_N = _VAR_N_TABLE[var_n_key]
    var_V = _VAR_V_TABLE[var_v_key]
    tau = df_premia.loc[
        df_premia["my_educ"] == tau_educ,
        f"risk_premium_{tau_parent}"
    ].values[0]
    return {**par_base, "var_N": var_N, "var_V": var_V,
            "tau": tau, "repl_rate": repl, "a0": a0}


# ------------------------------------------------------------------
# Helper: unpack simulation output into lifecycle moment arrays
# ------------------------------------------------------------------
def _lifecycle_moments(out, T):
    _, norm_a, sim_alpha, X, A, Y, _, _, _, _ = out
    C_arr = X - A
    mean_Y = Y.mean(axis=0);     std_Y = Y.std(axis=0)
    mean_A = A.mean(axis=0);     std_A = A.std(axis=0)
    mean_C = C_arr.mean(axis=0); std_C = C_arr.std(axis=0)
    mean_alpha = np.full(T, np.nan); std_alpha = np.full(T, np.nan)
    for t in range(T):
        mask = norm_a[:, t] > 0
        if mask.any():
            mean_alpha[t] = sim_alpha[mask, t].mean()
            std_alpha[t]  = sim_alpha[mask, t].std()
    return (Y, A, norm_a, sim_alpha,
            mean_Y, std_Y, mean_A, std_A,
            mean_C, std_C, mean_alpha, std_alpha)


