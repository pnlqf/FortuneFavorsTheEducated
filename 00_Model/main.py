def _income_key(path):
    """Reverse-lookup: income path array → path name ("econ" / "masters" / "primary")."""
    return next((k for k, v in PATHS.items() if v == path), "econ")

_EDU_NAME    = {"econ": "Econ", "master": "Master's", "primary": "Primary"}
_PARENT_NAME = {"econ": "Econ parents", "master": "Master's parents",
                "primary": "Primary parents", "avg": "Avg. parents",
                "median": "Median parents"}
_REPL_RATE   = {"econ": 0.892, "master": 0.893, "primary": 0.914}

def _resolve_repl(val):
    """Accept a label string ("econ"/"master"/"primary") or a raw number."""
    if isinstance(val, str):
        return _REPL_RATE[val]
    return float(val)

def _auto_label(tau_educ, tau_parent):
    return f"{_EDU_NAME.get(tau_educ, tau_educ)} w. {_PARENT_NAME.get(tau_parent, tau_parent)}"

def _lookup_a0(tau_educ, tau_parent):
    """Look up starting normalised assets from the WIR-at-25 table."""
    col = f"parent_{tau_parent}"
    return float(df_wir.loc[tau_educ, col])

